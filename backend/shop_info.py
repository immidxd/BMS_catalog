def _drafts_visible() -> bool:
    return os.getenv("SHOP_INFO_DRAFT", "").strip().lower() in ("1", "true", "yes", "on")


def how_to_buy() -> List[Dict[str, Any]]:
    """Блоки для вітрини. Непідтверджені — лише коли явно ввімкнено."""
    show_draft = _drafts_visible()
    return [
        {"title": s["title"], "items": s["items"], "draft": bool(s.get("draft"))}
        for s in SECTIONS
        if show_draft or not s.get("draft")
    ]
