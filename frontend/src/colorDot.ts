const MULTI = new Set(['різнокольоровий', 'мультиколор']);
const RAINBOW = 'conic-gradient(#e53935, #fdd835, #43a047, #1e88e5, #8e24aa, #e53935)';

const norm = (s: string) => s.toLowerCase().replace(/[‐‑–]/g, '-').replace(/[’ʼ`]/g, "'").replace(/\s+/g, ' ').trim()
  .replace(/\b(темно|світло|ніжно|блідо|яскраво) (?=\S)/g, '$1-')   // «темно синій» = «темно-синій»
  .replace(/коричневый/g, 'коричневий').replace(/помарчев/g, 'помаранчев');   // одруки з BMS

// «сіро» → «сірий», «синьо» → «синій»: перша частина складеного кольору
const stem = (part: string): string | undefined =>
  SHADES[part] ?? SHADES[part.replace(/ьо$/, 'ій')] ?? SHADES[part.replace(/о$/, 'ий')];

const shadesOf = (token: string): string[] | null => {
  if (SHADES[token]) return [SHADES[token]];
  const parts = token.split('-');
  if (parts.length > 1) {
    const hex = parts.map(stem);
    if (hex.every(Boolean)) return hex as string[];
  }
  return null;
};

/** CSS-фон кружечка або null, якщо колір не впізнали (тоді кружечка нема). */
export const colorDotBackground = (name: string | null | undefined): string | null => {
  if (!name) return null;
  const tokens = norm(name).split(/\s*[/,+]\s*|\s+(?:з|і|та)\s+/).filter(Boolean);
  if (tokens.some((t) => MULTI.has(t))) return RAINBOW;
  const hex: string[] = [];
  for (const t of tokens) {
    const found = shadesOf(t);
    if (!found) return null;
    hex.push(...found.filter((h) => !hex.includes(h)));
  }
  if (hex.length === 0) return null;
  if (hex.length === 1) return hex[0];
  const step = 100 / hex.length;
  return hex.length === 2
    ? `linear-gradient(135deg, ${hex[0]} 50%, ${hex[1]} 50%)`
    : `conic-gradient(${hex.map((h, i) => `${h} ${i * step}% ${(i + 1) * step}%`).join(', ')})`;
};
